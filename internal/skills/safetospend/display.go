package safetospend

import (
	"fmt"
	"strings"
)

// Валюта ОТОБРАЖЕНИЯ конвертов.
//
// Хранение долей не трогается: allocated / carried_in остаются в THB — единой
// расчётной валюте проекта (ADR-008 §7). Меняется только представление, то есть
// последний шаг перед печатью. Это принципиально: если бы валюту отображения
// пустили внутрь расчёта, остаток доли начал бы дрейфовать от движения курса
// без единой траты — ровно то, что §7 запрещает.
//
// Дефолт — THB: оператор живёт и тратит в батах, а рубли ему нужны как перевод
// («сколько это дома»), а не как основная шкала.

// DefaultDisplayCurrency — валюта конвертов, когда её не назвали.
const DefaultDisplayCurrency = "THB"

// Display — как печатать сумму, хранящуюся в THB.
//
// Курс лежит внутри и рядом с кодом валюты не случайно: печать обязана
// показывать те же деньги, по которым посчитаны доли. Разъехавшиеся «код
// валюты отдельно, курс отдельно» уже дали бы возможность напечатать баты по
// рублёвому числу.
type Display struct {
	Code      string  // "THB" | "RUB" (прочие коды — как есть)
	RubPerTHB float64 // ₽ за 1 ฿
}

// NewDisplay собирает валюту отображения. Пустой / неизвестный код — дефолт THB.
//
// Неизвестная валюта тоже уводится в дефолт, а не печатается своим кодом: у нас
// нет курса ни к чему, кроме рубля (rates["THB"] = ₽ за ฿), и напечатать сумму
// «в долларах» мы бы всё равно не смогли — получились бы баты с чужим знаком.
func NewDisplay(code string, rubPerTHB float64) Display {
	switch strings.ToUpper(strings.TrimSpace(code)) {
	case "RUB", "RUR", "₽":
		return Display{Code: "RUB", RubPerTHB: rubPerTHB}
	default:
		return Display{Code: DefaultDisplayCurrency, RubPerTHB: rubPerTHB}
	}
}

// Amount переводит хранимую сумму THB в валюту отображения.
func (d Display) Amount(thb float64) float64 {
	if d.Code == "RUB" {
		return thb * d.RubPerTHB
	}
	return thb
}

// Sign — знак валюты для печати.
func (d Display) Sign() string {
	if d.Code == "RUB" {
		return "₽"
	}
	return "฿"
}

// Fmt — готовая строка «сумма знак». Единственная точка, где число встречается
// со знаком валюты: пока формат собирался руками в каждом Fprintf, ничто не
// мешало напечатать рублёвое число с батовым знаком.
// Разряды группируются пробелом, копеек нет: негруппированные цифры человек
// считает справа налево, а десятые в сводке — шум (ресёрч вёрстки, п. П2.5).
func (d Display) Fmt(thb float64) string {
	return fmt.Sprintf("%s %s", groupDigits(roundInt(d.Amount(thb))), d.Sign())
}

// ParseDisplayCurrency вытаскивает валюту конвертов из фразы оператора:
// «покажи конверты в рублях» → RUB, «в батах» → THB. Не нашли — "" (решает
// вызывающий, у него есть свой дефолт).
//
// Разбор по тексту нужен как страховка рядом с полем в input скилла: поле
// заполняет LLM, и её молчание не должно превращаться в «оператор не просил».
// Ищем корень С ПРЕДЛОГОМ («в рублях»), а не голый корень: тот же разбор служит
// страховкой поверх описания траты в budget-скилле, и «купил рубленый стейк»
// молча переключал бы весь ответ на рубли.
func ParseDisplayCurrency(text string) string {
	t := strings.ToLower(text)
	for _, w := range []string{"в рубл", "в ₽", "в rub"} {
		if strings.Contains(t, w) {
			return "RUB"
		}
	}
	for _, w := range []string{"в бат", "в ฿", "в thb"} {
		if strings.Contains(t, w) {
			return "THB"
		}
	}
	return ""
}

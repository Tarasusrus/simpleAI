package safetospend

import "time"

// Настроечные параметры skill'а — единый именованный блок (конвенция ADR-006:
// пороги/константы поведения не разбросаны по коду, а собраны и обоснованы).
// Горизонт по умолчанию берётся из budget.DefaultHorizonDays (общий домен).
const (
	// forecastMonths — окно истории для прогноза бытовых трат.
	forecastMonths = 3
	// prorationBaseDays — прогноз даётся месячным; делим на 30 при пересчёте к
	// длине периода (days/prorationBaseDays).
	prorationBaseDays = 30.0
	// regularIncomeTolerance — |отклонение| прихода от регулярного дохода, при
	// котором приход считается «регулярным» (±15%).
	regularIncomeTolerance = 0.15
	// categoriesTopN — сколько категорий показывать в разбивке «на что уйдут»,
	// остальные сворачиваются в «прочее».
	categoriesTopN = 5
	// defaultLLMTimeout — таймаут LLM-нарратива, независимый от Telegram-хендлера.
	defaultLLMTimeout = 45 * time.Second
	// minShareMonthlyTHB — минимальный МЕСЯЧНЫЙ лимит категории, ниже которого
	// отдельный конверт не заводится: копеечные лимиты человек не отслеживает,
	// они только шумят в раскладке. Такие категории сливаются в «прочее».
	//
	// Планка абсолютная и от прихода НЕ зависит — это регрессия simpleAI-faeq.10.
	// Порог «доля свободных денег» двигался вместе с обязательствами (сдвинулась
	// next_date платежа — сдвинулся порог), и категория с постоянным прогнозом
	// перепрыгивала его туда-обратно: «Транспорт 985» и «Здоровье 798» то были
	// конвертами, то молча уезжали в «прочее» и накопления. Набор конвертов —
	// свойство трат человека, а не остатка после обязательств.
	//
	// Пересчитывается на длину периода теми же days/prorationBaseDays, что и сам
	// прогноз: сравнивать месячную планку с недельным лимитом нельзя.
	minShareMonthlyTHB = 500.0
	// minHistoryMonths — минимум ПОЛНЫХ месяцев истории по категории, чтобы
	// назначать ей собственный лимит. Меньше — среднее по одному месяцу является
	// не статистикой, а случайным числом; лимит не выдумываем (ADR-008).
	minHistoryMonths = 2
	// savingsShareName — имя доли-накопления: в неё уходит всё, что не покрыто
	// лимитами трат. Kind = budget.ShareKindSave, остаток переносится дальше.
	savingsShareName = "накопления"
	// adviceLineRunes — предел длины одной строки совета от LLM, В СИМВОЛАХ.
	// Байтовый предел на кириллице резал бы символ пополам.
	adviceLineRunes = 200
	// lowDataNamesShown — сколько категорий без истории называть поимённо в
	// предупреждении. Остальные сворачиваются в «и ещё N»: живой прогон дал
	// одиннадцать таких категорий, и одиннадцать строк шума прятали сам ответ.
	lowDataNamesShown = 3
	// fixedFundingDays — окно финансирования регулярных платежей: платёж
	// финансируется этим приходом, если его дата попадает в месяц вперёд от
	// начала периода. Не период конверта: аренда 10.09 при периоде до 06.09 всё
	// равно должна быть отложена сейчас, иначе платёж встретит пустой карман
	// (sinking fund). Месяц — потому что все регулярные платежи месячные, и
	// более широкое окно заложило бы один платёж дважды.
	fixedFundingDays = 31
	// kopecksInUnit — округление сумм долей до копейки: раскладка показывается
	// человеку, а не хранит доли рубля.
	kopecksInUnit = 100.0
)

// lowShareFraction — доля лимита, ниже которой конверт помечается жёлтым
// («скоро кончится»). Порог отображения, на счёт не влияет.
const lowShareFraction = 0.2
